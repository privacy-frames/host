import { createContext, evaluate } from './engine';
const context = await createContext();
globalThis.contextAudio = async () => {
  const guest = context.newArrayBuffer(new Float32Array(256).buffer);
  context.setProp(context.global, 'samples', guest);
  evaluate(context, 'new Float32Array(samples).fill(0.125)');
  const view = context.getArrayBuffer(guest);
  const copied = new Float32Array(view.value.buffer, view.value.byteOffset, 256).slice();
  view.dispose();
  guest.dispose();
  const audio = new OfflineAudioContext(1, 256, 48000);
  const buffer = audio.createBuffer(1, 256, 48000);
  buffer.copyToChannel(copied, 0);
  const source = audio.createBufferSource();
  source.buffer = buffer;
  const analyser = audio.createAnalyser();
  analyser.fftSize = 32;
  source.connect(analyser);
  analyser.connect(audio.destination);
  source.start();
  const rendered = await audio.startRendering();
  const frequencies = new Float32Array(analyser.frequencyBinCount);
  analyser.getFloatFrequencyData(frequencies);
  const returned = context.newArrayBuffer(frequencies.buffer);
  context.setProp(context.global, 'frequencies', returned);
  const bins = evaluate(context, 'new Float32Array(frequencies).length');
  returned.dispose();
  return { guestToAudioSample: rendered.getChannelData(0)[0], analyserToGuestBins: bins };
};
